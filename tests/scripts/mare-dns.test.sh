#!/usr/bin/env bash
# shell/mare/scripts/mare-dns: o estado (o arquivo do Mk e o resolv.conf), a
# troca do DNS global pelo ajudante (com o pkexec, o nmcli e o getent falsos e
# uma raiz de mentira), o teste de resolução e o `soltar` da conexão em uso.
. "$(dirname "$0")/../lib.sh"

dns_sh=$REPO/shell/mare/scripts/mare-dns
R=$SBX/root
conf=$R/etc/NetworkManager/conf.d/90-mk-dns.conf
resolv=$R/etc/resolv.conf
helper=$R/usr/lib/mk/mk-dns
sd=$XDG_RUNTIME_DIR/mare-dns
nm=$SBX/nm
mkdir -p "$R/etc/NetworkManager/conf.d" "$nm"
install -Dm755 "$REPO/system/mk/mk-dns" "$helper"

# O pkexec de mentira roda o ajudante de verdade na raiz falsa; com
# $SBX/pkexec.rc, sai com esse código sem rodar nada (senha negada).
stub pkexec '[[ -f $SBX/pkexec.rc ]] && exit "$(<"$SBX/pkexec.rc")"
MK_ROOT=$SBX/root exec "$@"'
# O nmcli de mentira: com -g os ":" e as "\" saem escapados (a não ser com
# "-e no"), e `con mod` só aceita o nome exato da conexão. Cada chamada fica
# também em $SBX/args, com um [ ] por argumento.
#   $nm/conn nome da conexão    $nm/ignore  as duas linhas do ignore-auto-dns
#   $nm/mod.rc, $nm/reapply.rc, $nm/reload.rc  código de saída
stub nmcli '
printf "[%s]" "$@" >>"$SBX/args"; echo >>"$SBX/args"
nm=$SBX/nm esc=1 prev=""
for a in "$@"; do [[ $prev == -e && $a == no ]] && esc=0; prev=$a; done
case " $* " in
  *" GENERAL.CONNECTION dev show "*)
    if ((esc)); then sed '"'"'s/[\\:]/\\&/g'"'"' "$nm/conn"; else cat "$nm/conn"; fi ;;
  *" ipv4.ignore-auto-dns,ipv6.ignore-auto-dns con show "*)
    [[ ${@: -1} == "$(<"$nm/conn")" ]] || exit 10
    if [[ -f $nm/ignore ]]; then cat "$nm/ignore"; else printf "no\nno\n"; fi ;;
  " con mod "*)
    [[ $3 == "$(<"$nm/conn")" ]] || { echo "Error: unknown connection '"'"'$3'"'"'." >&2; exit 10; }
    [[ -f $nm/mod.rc ]] && { echo "Error: Failed to modify connection: Insufficient privileges" >&2; exit "$(<"$nm/mod.rc")"; } ;;
  " dev reapply "*)
    [[ -f $nm/reapply.rc ]] && { echo "Error: Reapply failed" >&2; exit "$(<"$nm/reapply.rc")"; }
    echo "Connection successfully reapplied to device." ;;
  *" general reload conf "* | *" general reload dns-rc "*)
    [[ -f $nm/reload.rc ]] && { echo "Error: NetworkManager is not running." >&2; exit "$(<"$nm/reload.rc")"; } ;;
  *) exit 2 ;;
esac
exit 0'
stub notify-send
stub qs 'case " $* " in *" mare state "*) cat "$SBX/mare-state" ;; esac'

# A casa de sempre: Wi-Fi "Casa", o roteador no resolv.conf, nenhum arquivo do
# Mk, o nome resolve e a folha dos Ajustes fechada.
casa() { # casa [conexão] [interface]
  rm -rf "${sd:?}" "${conf:?}"
  rm -f "$nm"/*.rc "$nm/ignore" "$SBX/pkexec.rc" "$SBX/pwn"*
  printf '%s\n' "${1:-Casa}" >"$nm/conn"
  stub ip "echo '1.1.1.1 via 192.168.1.1 dev ${2:-wlan0} src 192.168.1.50 uid 1000'; echo '    cache'"
  stub getent 'echo "95.217.163.246  archlinux.org"'
  printf '# Generated by NetworkManager\nsearch lan\nnameserver 192.168.1.1\n' >"$resolv"
  echo rest >"$SBX/mare-state"
  calls_reset
  : >"$SBX/args"
}
run() { MARE_DNS_ROOT=$R bash "$dns_sh" "$@"; }
# O mesmo, num sistema sem ip, nmcli, pkexec nem getent (um PATH só, que o
# path_sem custa caro).
sem=$(path_sem ip nmcli pkexec getent)
run_sem() { PATH=$sem MARE_DNS_ROOT=$R bash "$dns_sh" "$@"; }
# O resolv.conf como o NetworkManager o deixaria depois da troca.
usa() { printf 'nameserver %s\n' "$@" >"$resolv"; }
grava() { MK_ROOT=$R bash "$helper" aplicar "$@" && calls_reset; }
ultima() { tail -n1 <<<"$1"; }

