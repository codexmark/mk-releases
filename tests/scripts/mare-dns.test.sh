# Recusado antes de qualquer janela: sai com 2, diz o erro em JSON, e nem o
# pkexec nem o arquivo são tocados.
recusa() { # recusa <erro esperado> <args...>
  local esperado=$1 out rc
  shift
  calls_reset
  out=$(run "$@" 2>/dev/null)
  rc=$?
  [[ $rc == 2 ]] || _fail "$*: devia sair com 2, saiu com $rc"
  eq false "$(jq -r .ok <<<"$out")" "$*: ok"
  eq "$esperado" "$(jq -r .error <<<"$out")" "$*: erro"
  hasnt "$out" "elevating"
  not_called "pkexec"
  absent "$conf"
}

