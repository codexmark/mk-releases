// Entrada é um item de um tar ou zip de teste.
type Entrada struct {
	Nome     string
	Conteudo string
	Modo     int64 // zero vale 0644 (0755 numa pasta)
	// Tipo: 0 arquivo; 'd' pasta; 'l' link simbólico; 'h' link físico;
	// 'c' dispositivo; 'f' fifo.
	Tipo byte
	Alvo string
	// Tamanho, se não for zero, é o que o cabeçalho do tar declara (o
	// conteúdo é completado com zeros): para as bombas.
	Tamanho int64
}

// Tar monta um tar (sem compressão).
func Tar(entradas []Entrada) []byte {
	var b bytes.Buffer
	w := tar.NewWriter(&b)
	for _, e := range entradas {
		h := &tar.Header{Name: e.Nome, Mode: e.Modo, Size: int64(len(e.Conteudo)), Typeflag: tar.TypeReg, Format: tar.FormatPAX}
		if h.Mode == 0 {
			h.Mode = 0o644
		}
		switch e.Tipo {
		case 'd':
			h.Typeflag, h.Size = tar.TypeDir, 0
			if e.Modo == 0 {
				h.Mode = 0o755
			}
		case 'l':
			h.Typeflag, h.Linkname, h.Size = tar.TypeSymlink, e.Alvo, 0
		case 'h':
			h.Typeflag, h.Linkname, h.Size = tar.TypeLink, e.Alvo, 0
		case 'c':
			h.Typeflag, h.Size = tar.TypeChar, 0
		case 'f':
			h.Typeflag, h.Size = tar.TypeFifo, 0
		}
		if e.Tamanho != 0 {
			h.Size = e.Tamanho
		}
		if err := w.WriteHeader(h); err != nil {
			panic(err)
		}
		if h.Typeflag == tar.TypeReg {
			_, _ = w.Write([]byte(e.Conteudo))
			if falta := h.Size - int64(len(e.Conteudo)); falta > 0 {
				_, _ = w.Write(make([]byte, falta))
			}
		}
	}
	_ = w.Close()
	return b.Bytes()
}

// TarGz é o Tar comprimido com gzip.
func TarGz(entradas []Entrada) []byte {
	var b bytes.Buffer
	w := gzip.NewWriter(&b)
	_, _ = w.Write(Tar(entradas))
	_ = w.Close()
	return b.Bytes()
}

// Zip monta um zip. Com semModo, as entradas saem como as de um zip feito
// fora do Unix: sem permissões.
func Zip(entradas []Entrada, semModo bool) []byte {
	var b bytes.Buffer
	w := zip.NewWriter(&b)
	for _, e := range entradas {
		h := &zip.FileHeader{Name: e.Nome, Method: zip.Deflate}
		modo := fs.FileMode(e.Modo)
		if modo == 0 {
			modo = 0o644
		}
		conteudo := e.Conteudo
		switch e.Tipo {
		case 'd':
			modo = fs.ModeDir | 0o755
		case 'l':
			modo, conteudo = fs.ModeSymlink|0o777, e.Alvo
		case 'c':
			modo = fs.ModeDevice | fs.ModeCharDevice | 0o644
		case 'f':
			modo = fs.ModeNamedPipe | 0o644
		}
		if semModo {
			h.CreatorVersion = 0 // FAT: sem permissões do Unix
		} else {
			h.SetMode(modo)
		}
		f, err := w.CreateHeader(h)
		if err != nil {
			panic(err)
		}
		_, _ = f.Write([]byte(conteudo))
		if falta := e.Tamanho - int64(len(conteudo)); falta > 0 {
			_, _ = f.Write(make([]byte, falta))
		}
	}
	_ = w.Close()
	return b.Bytes()
}

