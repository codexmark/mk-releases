// Package falso gera, na memória, os arquivos que os testes do MkInstalar
// instalam: um AppImage de mentira (um ELF mínimo com a magia e um squashfs
// atrás), arquivos tar e zip (inclusive os maliciosos: `../`, links para
// fora, bombas, arquivos especiais) e um .PKGINFO. Nada daqui vai no binário.
package falso

import (
	"archive/tar"
	"archive/zip"
	"bytes"
	"compress/gzip"
	"encoding/binary"
	"io/fs"

	sq "mkutil/internal/squash/falso"
)

// ELF devolve um cabeçalho ELF de 64 bits mínimo e válido. Com dinamico, tem
// um PT_INTERP (como o runtime clássico do AppImage, que precisa da libfuse2).
// tipo é o byte da magia do AppImage (1 ou 2); zero deixa sem a magia.
func ELF(dinamico bool, tipo byte) []byte {
	le := binary.LittleEndian
	nph := 0
	if dinamico {
		nph = 1
	}
	shoff := 64 + 56*nph
	b := make([]byte, shoff+64)
	copy(b, []byte{0x7f, 'E', 'L', 'F', 2, 1, 1, 0})
	if tipo != 0 {
		copy(b[8:], []byte{'A', 'I', tipo})
	}
	le.PutUint16(b[16:], 2)  // ET_EXEC
	le.PutUint16(b[18:], 62) // x86-64
	le.PutUint32(b[20:], 1)
	le.PutUint64(b[32:], 64) // e_phoff
	le.PutUint64(b[40:], uint64(shoff))
	le.PutUint16(b[52:], 64) // e_ehsize
	le.PutUint16(b[54:], 56) // e_phentsize
	le.PutUint16(b[56:], uint16(nph))
	le.PutUint16(b[58:], 64) // e_shentsize
	le.PutUint16(b[60:], 1)  // e_shnum: só a seção nula
	if dinamico {
		le.PutUint32(b[64:], 3) // PT_INTERP
	}
	return b
}

// AppImage junta o ELF e um squashfs com os arquivos dados.
func AppImage(dinamico bool, arquivos []sq.Arquivo) []byte {
	return append(ELF(dinamico, 2), sq.Monta(arquivos, sq.Opcoes{Comprime: sq.Zlib, Fragmentos: true})...)
}

