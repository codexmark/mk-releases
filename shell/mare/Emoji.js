var tones = ["", "🏻", "🏼", "🏽", "🏾", "🏿"];

// Minúsculas e sem acento, como a busca dos Ajustes (Schema.fold).
function fold(s) {
    return String(s).toLowerCase().normalize("NFD").replace(/[̀-ͯ]/g, "");
}

// O emoji pronto para copiar: sem tom (0) ou com um dos cinco (1 a 5). Com
// tom, o U+FE0F que vinha depois da base sai, como manda o Unicode.
function withTone(c, tone) {
    var t = tone >= 1 && tone <= 5 && tone === Math.floor(tone) ? tones[tone] : "";
    return t === "" ? c.replace(/~/g, "") : c.replace(/~️?/g, t);
}

// As linhas viram objetos na primeira vez que alguém pergunta:
//   c  o emoji, com "~" onde entra o tom     s  o mesmo, sem tom
//   n  o nome para mostrar                   tone  aceita tom de pele
//   g  a categoria                           fn, fk, fe  textos da busca
//   fx  as palavras postas à mão, entre espaços (para achar uma inteira)
var all = null;
// Sem protótipo: "constructor" não é um grupo nem um emoji.
var byGroup = Object.create(null);
var byChar = Object.create(null);

function load() {
    if (all !== null)
        return;
    all = [];
    for (var gi = 0; gi < groups.length; gi++) {
        var g = groups[gi].key, lines = raw[g], list = [];
        for (var i = 0; i < lines.length; i++) {
            var p = lines[i].split("|");
            var e = { c: p[0], s: p[0].replace(/~/g, ""), n: p[1] || p[3], g: g, tone: p[0].indexOf("~") >= 0,
                      fn: fold(p[1]), fk: fold(p[2] + (p[4] ? " " + p[4] : "")), fe: p[3].toLowerCase(),
                      fx: p[4] ? " " + fold(p[4]) + " " : "" };
            list.push(e);
            all.push(e);
            byChar[e.s] = e;
        }
        byGroup[g] = list;
    }
    raw = null;
}

function list(group) {
    load();
    return byGroup[group] || [];
}

// Os recentes guardam só o emoji (sem tom); aqui voltam a ser linhas.
function fromChars(chars) {
    load();
    var out = [];
    for (var i = 0; i < (chars || []).length; i++)
        if (byChar[chars[i]])
            out.push(byChar[chars[i]]);
    return out;
}

// Quanto `w` casa com um texto: no começo, no começo de uma palavra, ou no meio.
function hit(text, w, start, word, inside) {
    var i = text.indexOf(w);
    if (i < 0)
        return 0;
    if (i === 0)
        return start;
    while (i > 0) {
        if (text[i - 1] === " " || text[i - 1] === "-")
            return word;
        i = text.indexOf(w, i + 1);
    }
    return inside;
}

// O nome começa com a palavra inteira ("café", e não "cafeteira")?
function leads(name, w) {
    return name.lastIndexOf(w, 0) === 0 && (name.length === w.length || name[w.length] === " ");
}

// Todas as palavras digitadas têm de casar. O nome em português pesa mais
// que as palavras de busca, e estas mais que o nome em inglês. Uma palavra
// posta à mão e digitada inteira ("br", "eua", "joinha") ganha de um começo
// de nome ("braço"), mas perde para o nome que começa com a palavra inteira.
// No empate, vale a ordem do Unicode. Com `limit`, devolve só as primeiras.
function search(query, limit) {
    load();
    var words = fold(query).split(/\s+/).filter(function (w) { return w.length > 0; });
    if (words.length === 0)
        return [];
    var found = [];
    for (var i = 0; i < all.length; i++) {
        var e = all[i], total = 0;
        for (var j = 0; j < words.length; j++) {
            var w = words[j];
            var s = Math.max(hit(e.fn, w, 100, 80, 50), hit(e.fk, w, 70, 60, 35), hit(e.fe, w, 45, 40, 20));
            if (s === 100 && leads(e.fn, w))
                s = 120;
            else if (e.fx !== "" && e.fx.indexOf(" " + w + " ") >= 0)
                s = 110;
            if (s === 0) {
                total = 0;
                break;
            }
            total += s;
        }
        if (total > 0)
            found.push({ e: e, s: total, i: i });
    }
    found.sort(function (a, b) { return b.s - a.s || a.i - b.i; });
    return (limit ? found.slice(0, limit) : found).map(function (f) { return f.e; });
}
